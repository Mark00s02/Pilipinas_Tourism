"""Build the map home screen's province outlines: assets/map/ph-map.js.

Source: geoBoundaries PHL ADM2 (provinces; NAMRIA/PSA/OCHA, CC BY 3.0 IGO), simplified with mapshaper.
Projection: equirectangular with x scaled by cos(12.5 deg) - close enough to true shape across the islands.
Usage: python tools/build_map.py
"""
import json
import math
import os
import subprocess
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = os.path.join(ROOT, 'tools', '.cache', 'map')
OUT = os.path.join(ROOT, 'assets', 'map', 'ph-map.js')
API = 'https://www.geoboundaries.org/api/current/gbOpen/PHL/ADM2/'
PX_PER_DEG = 60
PROJ = {'lon0': 116.8, 'lat1': 21.3, 'kx': PX_PER_DEG * math.cos(math.radians(12.5)), 'ky': PX_PER_DEG}
DEST_PROVINCES = {
    'batanes': 'Batanes', 'vigan': 'Ilocos Sur', 'banaue': 'Ifugao', 'mayon': 'Albay', 'boracay': 'Aklan',
    'el-nido': 'Palawan', 'cebu': 'Cebu', 'bohol': 'Bohol', 'siargao': 'Surigao del Norte', 'dabaw': 'Davao del Sur',
}


def project(lon, lat):
    return (round((lon - PROJ['lon0']) * PROJ['kx'], 1), round((PROJ['lat1'] - lat) * PROJ['ky'], 1))


def ring_to_path(ring):
    pts, last = [], None
    for lon, lat in ring:
        p = project(lon, lat)
        if p != last:
            pts.append(p)
            last = p
    if len(pts) > 1 and pts[-1] == pts[0]:
        pts.pop()
    fmt = lambda v: ('%g' % v)  # noqa: E731
    return 'M' + 'L'.join(f'{fmt(x)} {fmt(y)}' for x, y in pts) + 'Z'


def fetch_source():
    os.makedirs(CACHE, exist_ok=True)
    src = os.path.join(CACHE, 'adm2.geojson')
    if not os.path.exists(src):
        meta = json.load(urllib.request.urlopen(urllib.request.Request(API, headers={'User-Agent': 'ph-explorer-map'}), timeout=60))
        with urllib.request.urlopen(meta['simplifiedGeometryGeoJSON'], timeout=120) as r, open(src, 'wb') as f:
            f.write(r.read())
    return src


def simplify(src, pct):
    out = os.path.join(CACHE, f'adm2-{pct}.geojson')
    subprocess.run(['npx', '-y', 'mapshaper@0.6.121', src, '-simplify', f'{pct}%', 'keep-shapes', '-filter-islands', 'min-area=4km2',
                    '-o', out, 'precision=0.001', 'force'], check=True, shell=(os.name == 'nt'))
    return json.load(open(out, encoding='utf-8'))


def build(pct=10):
    geo = simplify(fetch_source(), pct)
    paths = []
    for f in geo['features']:
        name, g = f['properties']['shapeName'], f['geometry']
        if not g:
            continue
        polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
        d = ''.join(ring_to_path(ring) for poly in polys for ring in poly[:1])  # outer rings only
        paths.append(f'<path data-province="{name}" d="{d}"/>')
    names = {f['properties']['shapeName'] for f in geo['features']}
    missing = [p for p in DEST_PROVINCES.values() if p not in names]
    if missing:
        sys.exit(f'missing provinces: {missing}')
    w, h = project(127.0, 4.4)
    svg = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w:g} {h:g}" role="img" aria-label="Map of the Philippines">{"".join(paths)}</svg>'
    js = ('// Generated by tools/build_map.py from geoBoundaries PHL ADM2 (CC BY 3.0 IGO). Do not edit by hand.\n'
          f'window.PH_MAP_PROJ={json.dumps(PROJ)};\nwindow.PH_MAP_SVG={json.dumps(svg)};\n')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(js)
    print(f'{len(paths)} provinces, {len(js) / 1024:.0f} KB -> {OUT}')
    return len(js)


if __name__ == '__main__':
    size, pct = build(), 10
    while size > 150 * 1024 and pct > 1:
        pct -= 1
        size = build(pct)
