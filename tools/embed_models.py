"""Embed optimized models as scripts (so file:// works) and write their credits.

Pipeline: fetch_model.py (download) -> gltf-transform optimize -> strip_models.mjs -> this script.
python tools/embed_models.py      # reads tools/.cache/models/*.final.glb and tools/credits/models.jsonl
  -> assets/models/<name>.glb.js  (loaded on demand by assets/js/models.js)
  -> assets/js/model-credits.js   (window.PH_MODEL_CREDITS, loaded up front for the page footers)
"""
import base64
import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'tools', '.cache', 'models')
OUT = os.path.join(ROOT, 'assets', 'models')
LICENSE_URLS = {'CC0': 'https://creativecommons.org/publicdomain/zero/1.0/', 'CC-BY': 'https://creativecommons.org/licenses/by/3.0/'}

credits = {}
for line in open(os.path.join(ROOT, 'tools', 'credits', 'models.jsonl'), encoding='utf-8'):
    r = json.loads(line)
    credits[r['name']] = {k: r[k] for k in ('title', 'author', 'license', 'url')}

used = {}
for path in sorted(glob.glob(os.path.join(SRC, '*.final.glb'))):
    name = os.path.basename(path)[:-len('.final.glb')]
    c = credits[name]
    c['licenseUrl'] = next(u for k, u in LICENSE_URLS.items() if c['license'].upper().startswith(k))
    data = open(path, 'rb').read()
    with open(os.path.join(OUT, f'{name}.glb.js'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(f"// {c['title']} by {c['author']} ({c['license']}) {c['url']} — optimized: 256px WebP textures, quantized, no animation.\n"
                f"window.PH_MODELS=window.PH_MODELS||{{}};window.PH_MODELS['{name}']='{base64.b64encode(data).decode()}';\n")
    used[name] = c
    print(f'{name:11} {len(data) // 1024:4} KB')

with open(os.path.join(ROOT, 'assets', 'js', 'model-credits.js'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by tools/embed_models.py — credits for the 3D models in assets/models.\n'
            f'window.PH_MODEL_CREDITS={json.dumps(used, ensure_ascii=False, indent=1)};\n')

# Drop embedded models that are no longer part of the set (the eagle is managed separately).
for js in glob.glob(os.path.join(OUT, '*.glb.js')):
    n = os.path.basename(js)[:-len('.glb.js')]
    if n != 'eagle' and n not in used:
        os.remove(js)
        print(f'removed {n}.glb.js')
